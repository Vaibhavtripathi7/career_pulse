// Writes RESULTS.md from a run's results. The analysis section between the
// markers is written by hand and kept when the file is regenerated.
import fs from "node:fs";
import type { Results, ScalingRun } from "../run.ts";
import { median } from "./stats.ts";

const START = "<!-- ANALYSIS:START -->";
const END = "<!-- ANALYSIS:END -->";
const WORKER_CONCURRENCY = 2; // src/email.worker.ts

const int = (n: number) => Math.round(n).toLocaleString("en-US");
const fix = (n: number | null | undefined, d = 1) => (n === null || n === undefined || Number.isNaN(n) ? "n/a" : n.toFixed(d));

function med(runs: ScalingRun[], pick: (r: ScalingRun) => number | null): number {
  const values = runs.map(pick).filter((v): v is number => v !== null && !Number.isNaN(v));
  return values.length ? median(values) : Number.NaN;
}

export function writeReport(file: string, r: Results, withAnalysis = true): void {
  const previous = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  const kept = previous.includes(START) && previous.includes(END)
    ? previous.slice(previous.indexOf(START), previous.indexOf(END) + END.length)
    : `${START}\n_Not written yet._\n${END}`;

  const s = r.specs;
  const o = r.oracle;
  const lines: string[] = [];
  const add = (...l: string[]) => lines.push(...l);

  add(
    "# Load test: Gmail ingestion pipeline",
    "",
    `Generated by \`${r.command}\` on ${r.generatedAt.slice(0, 16).replace("T", " ")} UTC at commit \`${r.versions.commit}\`. ` +
      "Raw numbers are in `results/latest.json`; how to rerun is in `README.md`.",
    "",
    "## Machine",
    "",
    "| | |",
    "|---|---|",
    `| CPU | ${s.cpuModel}, ${s.physicalCores} cores / ${s.logicalCpus} threads${s.maxMHz ? `, ${s.maxMHz} MHz nominal (boost enabled)` : ""} |`,
    `| RAM | ${s.ramGiB} GiB (${int(s.memAvailableMB)} MB available at start) |`,
    `| OS | ${s.os}, kernel ${s.kernel} |`,
    `| Software | Node ${s.node}, PostgreSQL ${r.versions.postgres}, Redis ${r.versions.redis}, BullMQ ${r.versions.bullmq}, Docker ${s.docker} |`,
    `| Load average at start | ${s.loadAverage.join(" / ")} (a laptop with other apps open, not an isolated server) |`,
    "",
    "## Workload",
    "",
    `- **${int(r.config.messages)} unique synthetic messages** across ${int(r.config.users)} users ` +
      `(${int(r.config.messages / r.config.users)} each), plus **${int(o.deliveries - o.uniqueMessages)} exact duplicates** ` +
      `(same ID, same content) = **${int(o.deliveries)} Gmail deliveries per run**.`,
    `- ${int(o.byKind.job.unique)} job-application emails (${fix((o.byKind.job.unique / o.uniqueMessages) * 100, 0)}%) and ` +
      `${int(o.byKind.promo.unique)} promo/other emails, from ${Object.keys(o.byTemplate).length} templates. Message IDs are stable 16-hex strings.`,
    `- One BullMQ job per user, which is production's unit of work (\`fetchemails(userId)\`): ${int(r.config.users)} jobs per run. ` +
      `Each worker process runs production's worker unchanged, with concurrency ${WORKER_CONCURRENCY}.`,
    "- Production code is not modified. `googleapis` and the Gemini fallback are swapped for local fakes by ESM resolve hooks, " +
      "and any non-loopback TCP connection is refused. `NODE_ENV=production`: pino JSON logs at info (to /dev/null) and Postgres over TLS.",
    `- **Oracle:** the production parser, run over every unique message, accepts **${int(o.expectedRows)}** of them, so that is the ` +
      `exact row count a complete sync must produce. It stores ${int(o.byKind.job.stored)} of ${int(o.byKind.job.unique)} job emails ` +
      `and ${int(o.byKind.promo.stored)} of ${int(o.byKind.promo.unique)} promos. It predicts **${int(o.llmCallsPerPass)} LLM-fallback calls ` +
      `per pass** (${int(o.llmCallsUnique)} unique messages, re-parsed when duplicated).`,
    `- **Single-threaded pipeline cost** (parser + body extraction, no queue or database): ` +
      `${fix((o.pipelineMs * 1000) / o.uniqueMessages, 0)} µs per message, ${int(o.uniqueMessages / (o.pipelineMs / 1000))} msgs/s. ` +
      `Generating the synthetic source costs another ${fix((o.generateMs * 1000) / o.deliveries, 0)} µs per delivery, which the workers also pay.`,
    "",
  );

  if (r.scaling.length) {
    const byN = new Map<number, ScalingRun[]>();
    for (const run of r.scaling) byN.set(run.workers, [...(byN.get(run.workers) ?? []), run]);
    const base = med(byN.get(Math.min(...byN.keys())) ?? [], (x) => x.msgsPerSec);
    const repeats = Math.max(...[...byN.values()].map((v) => v.length));

    add(
      `## Scaling: ${[...byN.keys()].join(", ")} worker processes (median of ${repeats} run${repeats === 1 ? "" : "s"} each)`,
      "",
      "| Worker processes | Max jobs in flight | Messages/s (min to max) | Speedup | Queue drain time | Job latency p50 / p95, exact | Job latency p50 / p95, from `email_sync_duration_seconds` | Rows match oracle |",
      "|---:|---:|---:|---:|---:|---:|---:|---|",
    );
    for (const [n, runs] of byN) {
      const mps = med(runs, (x) => x.msgsPerSec);
      const all = runs.map((x) => x.msgsPerSec);
      const ok = runs.every((x) =>
        x.verify.pass && x.llmCalls === o.llmCallsPerPass && x.failedJobs === 0 && x.deliveries === o.deliveries);
      add(
        `| ${n} | ${n * WORKER_CONCURRENCY} | **${int(mps)}** (${int(Math.min(...all))} to ${int(Math.max(...all))}) | ` +
          `${fix(mps / base, 2)}x | ${fix(med(runs, (x) => x.drainMs) / 1000, 1)} s | ` +
          `${int(med(runs, (x) => x.jobMs.p50))} / ${int(med(runs, (x) => x.jobMs.p95))} ms | ` +
          `${int(med(runs, (x) => x.histogram?.p50Ms ?? null))} / ${int(med(runs, (x) => x.histogram?.p95Ms ?? null))} ms | ` +
          `${ok ? `yes, ${runs.length} of ${runs.length}` : "**NO**"} |`,
      );
    }
    add(
      "",
      `- Messages/s counts every Gmail delivery a worker fetched and processed (${int(o.deliveries)} per run), divided by the queue drain time ` +
        "(first enqueue to last job finished). Each run's processed-delivery count was checked against that total.",
      `- **Exact** latency is BullMQ's \`finishedOn - processedOn\` for each of the ${int(r.config.users)} jobs: one user's whole sync. ` +
        "The **histogram** columns apply PromQL's " +
        "`histogram_quantile` algorithm to production's existing `email_sync_duration_seconds` metric, scraped from every worker. " +
        "Its lowest bucket is 0.5 s, so it cannot resolve faster syncs: see the analysis.",
      "- \"Rows match oracle\" means the database held exactly the oracle's (user, message) set (no missing, no extra, no duplicate rows), " +
        "every delivery was processed, the LLM stub count equalled the oracle's prediction, and no job failed.",
      "",
      `## Resources during the scaling runs (median)`,
      "",
      "| Worker processes | Worker CPU (cores) | CPU per worker | Machine CPU busy | Clock of busy cores | Postgres CPU (cores) | Redis CPU (cores) | Peak PG connections (TLS) | Redis commands/s | Peak worker RSS | Min RAM available |",
      "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    );
    for (const [n, runs] of byN) {
      add(
        `| ${n} | ${fix(med(runs, (x) => x.resources.workerCpuCores), 2)} | ${fix(med(runs, (x) => x.resources.perWorkerCpuPct), 0)}% | ` +
          `${fix(med(runs, (x) => x.resources.machineBusyPct), 0)}% | ${int(med(runs, (x) => x.resources.meanCpuMHz ?? null))} MHz | ` +
          `${fix(med(runs, (x) => x.resources.postgresCpuCores), 2)} | ` +
          `${fix(med(runs, (x) => x.resources.redisCpuCores), 2)} | ` +
          `${int(med(runs, (x) => x.resources.peakPgConnections))} (${int(med(runs, (x) => x.resources.peakPgTlsConnections))}) | ` +
          `${int(med(runs, (x) => x.resources.redisCommandsPerSec))} | ${int(med(runs, (x) => x.resources.peakWorkerRssMB))} MB | ` +
          `${int(med(runs, (x) => x.resources.minMemAvailableMB))} MB |`,
      );
    }
    add(
      "",
      "- CPU figures are CPU-seconds used during the drain window divided by its length, so 1.00 = one core fully busy. Workers are " +
        "read from `/proc/<pid>/stat`, Postgres and Redis from their containers' cgroup `cpu.stat`, the machine from `/proc/stat`. " +
        "\"Clock of busy cores\" averages each CPU's effective clock (`scaling_cur_freq`) weighted by how busy it was in each 200 ms sample.",
      "- Postgres connections are client backends on the load-test database, sampled every 200 ms (`pg_stat_activity` joined to " +
        "`pg_stat_ssl`), excluding the harness's own. Redis commands/s is the change in `total_commands_processed` over the window.",
      "",
    );
  }

  const a = r.adversarial;
  if (a) {
    const reasons = [...new Set(a.failedJobs.map((f) => f.reason))].join("; ") || "none";
    add(
      "## Adversarial run: duplicate enqueues and worker kills",
      "",
      "| | |",
      "|---|---|",
      `| Worker processes | ${a.workers}, one killed with SIGKILL every ~${fix(a.killEveryMs / 1000, 0)} s (jittered by up to 20%) and replaced at once |`,
      `| Jobs enqueued | ${int(a.jobsEnqueued)}: the same ${int(a.jobsEnqueued / a.batches)}-user batch ${a.batches} times, concurrently |`,
      `| Kills | ${a.kills.length} |`,
      `| Jobs in flight when killed | ${a.jobsInterrupted}: ${a.interruptedFate.completed} completed on a retry, ${a.interruptedFate.failed} failed, ${a.interruptedFate.unknown} unaccounted |`,
      `| Stalled-job events (BullMQ) | ${a.stalledEvents} (${a.stalledJobs} distinct jobs) |`,
      `| Jobs failed permanently | ${a.failedJobs.length} (${reasons}) |`,
      `| Users with no completed job | ${a.usersWithoutCompletedJob} |`,
      `| Queue drain time | ${fix(a.drainMs / 1000, 1)} s |`,
      `| Work done | ~${int(a.approxDeliveries)} deliveries processed, ${fix(a.approxDeliveries / o.deliveries, 2)}x one pass; ~${int(a.approxLlmCalls)} LLM-fallback calls |`,
      `| Rows / expected | ${int(a.verify.rows)} / ${int(a.verify.expected)} |`,
      `| Missing / extra / duplicate (userID, messageId) | ${a.verify.missing} / ${a.verify.extra} / ${a.verify.duplicateGroups} |`,
      `| **Assertion: rows == oracle, 0 duplicates, 0 lost** | **${a.verify.pass ? "PASS" : "FAIL"}** |`,
    );
    if (a.recovery) {
      add(
        `| Recovery (one re-sync of ${a.recovery.usersReenqueued} affected users, no kills) | ` +
          `${a.recovery.verify.pass ? "PASS" : "FAIL"}: ${int(a.recovery.verify.rows)} / ${int(a.recovery.verify.expected)} rows |`,
      );
    }
    add(
      "",
      "- The kill counts and \"work done\" for killed processes come from their last report before the kill (sent every 250 ms), " +
        "so they are approximate. The database check is exact.",
      "",
    );
  }

  if (withAnalysis) add("## Analysis", "", kept, "");
  fs.writeFileSync(file, lines.join("\n"));
}
